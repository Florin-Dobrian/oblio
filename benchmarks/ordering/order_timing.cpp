// order_timing.cpp - ordering time and fill, per method, on grid Laplacians in 2D and 3D.
//
// It measures rather than asserts, and nothing in the tree depends on it.
//
//   make run                          the default 2D sides, every method
//   make run3d                        the same, on cubic grids
//   make scale                        a wider ladder, one branch at a time, with gap columns
//   make scale3d                      the same, cubic
//   ./order_timing_cpp 200 280        any sides, every method
//   ./order_timing_cpp mmd 200 280    any sides, the MMD branch, with gap columns
//   ./order_timing_cpp amd 3d 20 26   any sides, the AMD branch, cubic
//
// Two optional words lead the sides, in either order: a BRANCH word, `mmd` or `amd`, and a SHAPE
// word, `2d` or `3d`. Both default to what this benchmark has always done, so the plain spellings
// are unchanged.
//
// The branch mode exists because the question it answers is not the same one. `run` asks what each
// method costs; `scale` asks how our layers' distance from the vendored routine MOVES with n,
// which is a ratio and is tedious to take off the wide table by hand. Same measurements either
// way, and the ratios are against the vendored routine in the same row, so nothing is compared
// across machines.
//
// THE SHAPE MODE IS NOT ANOTHER SIZE. A cubic grid is a different problem family, and the two
// families disagree about how good our orderings are: `experiments/ordering/REPORT.md` measured
// AMD1 beating the vendored AMD by 4 percent of fill in 2D and losing to it by 12 to 14 in 3D, on
// the same code. Every number recorded from this benchmark before 2026-08-09 came from the square
// grids alone, which is the flattering half of that picture, and the standing claim that our
// tie-break beats AMD's rests entirely on it. The two never share a table: a row is a matrix, and
// a column read down across two families is the error the second family exists to prevent.
//
// -O3 -DNDEBUG matters, and the Makefile carries it: the claim is about what an ordering costs,
// and at -O0 with asserts in it would measure something else. Every method is timed as the best of
// however many repeats fit a fixed wall time, after one warm-up, since a single cold reading is a
// reading and not a result.

