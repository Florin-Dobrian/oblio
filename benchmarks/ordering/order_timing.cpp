// THE HOOKED VENDORED AMD, which is an extra COLUMN and not a change to any existing one. The
// `AMD` column is `amd_order` exactly as SuiteSparse ships it, which is what a caller selecting
// `Ordering::AMD` gets, and it stays that. `AMDraw` is the same routine with an additive hook that
// reports the order AMD_2 would emit if it stopped at the end of its main loop, before
// AMD_postorder relabels it.
//
// WHY THE COLUMN EARNS ITS PLACE. AMD3 reproduces that raw order and deliberately does not
// postorder, so `AMD` is the wrong thing for it to sit against: the two are different permutations
// and their fill need not agree. It usually does, on every 2D grid and from 7 a side up in 3D, and
// it differs by one to three entries at 4^3, 5^3 and 6^3, because a postorder of AMD's ASSEMBLY
// tree is not fill-neutral. Its own header says that tree need not be the precise supernodal
// elimination tree, mass elimination under an approximate degree merging vertices that were never
// adjacent. Against `AMDraw` the comparison is exact by construction at every size, which is what
// a reader of this table wants to be able to check at a glance.
//
// The copy is GENERATED by tools/hook_amd.py from whatever private/Amd.cpp currently says,
// gitignored and removed by `make clean`, so no edited copy of vendored code can drift from the
// original unnoticed. The tool lives at the root rather than in experiments/ordering because
// benchmarks may not depend on a frozen study's contents; see ../README.md.
// Present only where private/ is, exactly as `Ordering::AMD` itself is: the Makefile defines
// OBLIO_AMD_RAW alongside OBLIO_VENDORED_ORDERINGS, and the column leaves the table with the
// vendored ones in a published build.
#ifdef OBLIO_AMD_RAW
static std::vector<int> gRaw;
extern "C" int amd_order_raw(int n, const int* Ap, const int* Ai, int* P,
                             double* Control, double* Info);
extern "C" void pbRawOrder(const int* raw, int n) { gRaw.assign(raw, raw + n); }
#endif

// THE TIMED VENDORED AMD, a second generated copy and a different instrument from the one above.
// The raw copy answers what order AMD_2 eliminates in and carries a vector per vertex to do it, so
// it is an oracle and cannot be timed; this one takes five timestamps and nothing else, so it can
// be timed and reports no order.
//
// WHAT IT IS FOR. Every ratio in this file is against `amd_order` whole, and two of its phases have
// no counterpart on our side: `AMD_aat` forms the pattern of A+A' because AMD takes a one-sided
// matrix, where ours arrives full-symmetric with the diagonal present, and `AMD_postorder` relabels
// the assembly tree, which `ElmForestEngine` redoes later on the exact supernodal tree with real
// front and update sizes. So `AMD3 1.82x` is measured against a denominator that includes work we
// deliberately do not do. This file has carried one estimate of that since 2026-08-01, 8 percent at
// 140 a side, taken from a single profile and never measured per size. `make phases2d` measures it,
// and the question it settles is not only the size of the correction but whether it is FLAT in n:
// the amd branch's 2D ratio grows from 1.25x to 1.82x across the ladder, and part of that would be
// the denominator rather than us if these phases were a falling share.
//
// The five phases and the comparable region are set out in tools/hook_amd.py. In brief,
// `build + core` is the vendored routine turning a caller's pattern into its working structure and
// then ordering it, which is what `orderAmd3` does from `QuotientGraph`'s constructor onward.
//
// IT IS CHECKED BEFORE IT IS READ, on the rule this tree keeps rediscovering: an instrument that
// silently declines to measure is worse than one that is absent. The copy must return the shipped
// routine's permutation entry for entry and its `Info[AMD_LNZ]` and `Info[AMD_NCMPA]` to the digit,
// and the row says so and refuses if it does not. And its own total is printed beside the unhooked
// `AMD` column, because a clock read is a compiler barrier: if the two disagree by more than this
// benchmark's noise, the instrumentation is distorting what it measures and the phases are not to
// be believed.
#ifdef OBLIO_AMD_TIMED
extern "C" int amd_order(int n, const int* Ap, const int* Ai, int* P,
                         double* Control, double* Info);
extern "C" int amd_order_timed(int n, const int* Ap, const int* Ai, int* P,
                               double* Control, double* Info);
extern "C" void amd_phase_ms(double out[5]);

// Amd.cpp's own indices into Info[], repeated here rather than included: the vendored header is
// not ours and this file takes nothing else from it. Same arrangement as amdorder.cpp's AMD_NDENSE.
static constexpr int AMD_NCMPA = 8;
static constexpr int AMD_LNZ   = 9;
#endif

// A pattern, from adjacency lists to full-symmetric CSC with the diagonal present, which is what a
// SparseMatrix holds. Shared by both builders below: they differ only in which neighbors they list.
static SparseMatrix<double> fromAdjacency(const std::vector<std::vector<int>>& adj,
                                          double diagonal) {
    const int n = static_cast<int>(adj.size());
    std::vector<std::size_t> colPtr(n + 1, 0);
    std::vector<std::int32_t> rowIdx;
    std::vector<double> val;
    for (int j = 0; j < n; ++j) {
        std::vector<int> col = adj[j];
        col.push_back(j);
        std::sort(col.begin(), col.end());
        for (int i : col) {
            rowIdx.push_back(static_cast<std::int32_t>(i));
            val.push_back(i == j ? diagonal : -1.0);
        }
        colPtr[j + 1] = rowIdx.size();
    }
    return SparseMatrix<double>(static_cast<std::size_t>(n), colPtr, rowIdx, val);
}

static SparseMatrix<double> grid2D(int m) {
    const int n = m * m;
    std::vector<std::vector<int>> adj(n);
    auto id = [&](int r, int c) { return r * m + c; };
    for (int r = 0; r < m; ++r)
        for (int c = 0; c < m; ++c) {
            const int u = id(r, c);
            if (r > 0)     adj[u].push_back(id(r - 1, c));
            if (c > 0)     adj[u].push_back(id(r, c - 1));
            if (r + 1 < m) adj[u].push_back(id(r + 1, c));
            if (c + 1 < m) adj[u].push_back(id(r, c + 1));
        }
    return fromAdjacency(adj, 4.0);            // the interior degree, as this builder always used
}

// The seven-point cubic grid, and it is a DIFFERENT PROBLEM FAMILY rather than a larger size. It
// fills far faster, makes larger cliques, and mass-eliminates much more often, and the two
// families do not agree about how good our orderings are: `experiments/ordering/REPORT.md`
// measured AMD1 beating the vendored AMD by 4 percent of fill in 2D and losing to it by 12 to 14
// in 3D, on the same code. Every number this benchmark had recorded before 2026-08-09 came from
// the square grids alone, which is the flattering half of that picture.
//
// The 2D row is a square and this one a cube, so the two are never rows of one table. A column
// read down across two families is exactly the mistake the second family exists to prevent.
static SparseMatrix<double> grid3D(int m) {
    const int n = m * m * m;
    std::vector<std::vector<int>> adj(n);
    auto id = [&](int x, int y, int z) { return (z * m + y) * m + x; };
    for (int z = 0; z < m; ++z)
        for (int y = 0; y < m; ++y)
            for (int x = 0; x < m; ++x) {
                const int u = id(x, y, z);
                if (z > 0)     adj[u].push_back(id(x, y, z - 1));
                if (y > 0)     adj[u].push_back(id(x, y - 1, z));
                if (x > 0)     adj[u].push_back(id(x - 1, y, z));
                if (x + 1 < m) adj[u].push_back(id(x + 1, y, z));
                if (y + 1 < m) adj[u].push_back(id(x, y + 1, z));
                if (z + 1 < m) adj[u].push_back(id(x, y, z + 1));
            }
    return fromAdjacency(adj, 6.0);            // the interior degree here, for the same reason
}

// Ordering time alone, in milliseconds: the best of however many repeats fit in `targetMs`, after
// one warm-up.
//
// The repeat count is CHOSEN FROM A TIMED PROBE rather than fixed, and that is not a refinement.
// Three trials of a 2.8 ms ordering is nine milliseconds of measurement, and two runs of an
// IDENTICAL BINARY disagreed by 4 percent on this benchmark. Five changes were landed inside that
// band during the 2026-08-08 amd work before anyone noticed the instrument was the constraint. The
// same fix was already in experiments/ordering/width.cpp, which is where this is copied from.
//
// The BEST of the repeats rather than the mean: a mean measures the machine's other work as well as
// ours, and the question here is what the code costs when nothing is in its way. The warm-up is
// discarded because the first ordering at a small size carries the core's clock ramp, which the
// minimum does not remove since the ramp outlasts the whole loop at n = 1024.
static constexpr double targetMs = 300.0;

// A column. Almost all of them are one of the library's orderings; `AMDraw` is not one, and giving
// it an enumerator in `Ordering` would put a benchmark's oracle into the library's public enum and
// into every switch over it. So the identity is local to this file.
//
// `MMD3B` is local for the same reason and is TEMPORARY. It is MMD3 on a different clique storage
// scheme, carried in src/Mmd3B.cpp with its own private copy of QuotientGraph so that the scheme
// can be measured before the class six drivers share is touched. It returns MMD3's permutation by
// construction, so its fill column carries nothing and its TIME column is the whole question. It
// is not in `Ordering`, not in the library's source list and not in the examples: it is reached
// here as a free function, so nothing outside this directory builds it. It comes out with the
// file when the question closes. See src/Mmd3B.cpp for the stop condition, and the section "The
// vendored storage scheme, and what it is worth" in experiments/ordering/README.md for what is
// being measured.
using OrderFn = std::vector<std::int32_t>(*)(const std::vector<std::size_t>&,
                                             const std::vector<std::int32_t>&);

struct Method {
    std::string name;
    Ordering    ordering;
    bool        raw = false;
    // Three columns are not orderings and so are not in `Ordering`: `AMDraw` is the vendored
    // routine through a hook, and `MMD3B` is a B layer, the same ordering on a different clique
    // storage scheme. Each is reached as a free function and flagged here, locally, for the reason
    // the header gives: an enumerator would put a benchmark's oracle into the library's public enum
    // and into every switch over it.
    //
    // THE AMD B LAYERS ARE GONE, 2026-08-16. AMD1B and AMD2B were their originals on a fused
    // eliminator schedule, and the schedule won: permutation-identical and faster on both families
    // once the tagged W removed the array crossing that had been paying for it, so it moved into
    // AMD1 and AMD2 and the files went. AMD3B, which carried the array folds, went with them, AMD3
    // now being identical to it. See docs/DESIGN_DECISIONS.md (2026-08-16).
    bool        mmd3b = false;
    OrderFn     fn = nullptr;    // a B layer reached directly; see below
};

// What either vendored copy takes: the off-diagonal pattern as `int`, where A holds both triangles
// with the diagonal present, so the conversion is a strip and a narrow. One function rather than
// one per consumer, since a second copy of it would be a second thing to keep in step and what it
// produces is a tie-break input: the order within a column decides which of several equal-degree
// vertices a bucket hands over first.
#if defined(OBLIO_AMD_RAW) || defined(OBLIO_AMD_TIMED)
static void patternNoDiagonal(const SparseMatrix<double>& A,
                              std::vector<int>& ap, std::vector<int>& ai) {
    const int n = static_cast<int>(A.size());
    ap.assign(n + 1, 0);
    ai.clear();
    for (int j = 0; j < n; ++j) {
        for (std::size_t cp = A.colPtr()[j]; cp < A.colPtr()[j + 1]; ++cp)
            if (A.rowIdx()[cp] != j) ai.push_back(A.rowIdx()[cp]);
        ap[j + 1] = static_cast<int>(ai.size());
    }
}
#endif

// The permutation the hooked routine produces.
static Permutation rawPermutation(const SparseMatrix<double>& A) {
#ifndef OBLIO_AMD_RAW
    (void) A;
    return Permutation();
#else
    const int n = static_cast<int>(A.size());
    std::vector<int> ap, ai;
    patternNoDiagonal(A, ap, ai);
    std::vector<int> perm(n);
    double control[5] = {static_cast<double>(n), 1.0, 0, 0, 0};   // dense off, aggressive on
    double info[20]   = {0};
    gRaw.clear();
    amd_order_raw(n, ap.data(), ai.data(), perm.data(), control, info);

    Permutation P;
    P.setNewToOld(std::vector<std::int32_t>(gRaw.begin(), gRaw.end()));
    return P;
#endif
}

// MMD3B's permutation, reached as a free function since it is not in `Ordering`. The body is
// `rawPermutation`'s, with the ordering call swapped: `setNewToOld` completes the other direction
// exactly as OrderEngine's loop does. This file's own note on measurement warns that a column
// reached one way times differently from a column reached another, so what differs between this
// path and MMD3's is the enum switch OrderEngine does before dispatching, one branch per call and
// not per vertex.
// The same shape as mmd3bPermutation below, for any B layer taken as a free function.
static Permutation fnPermutation(const SparseMatrix<double>& A, OrderFn f) {
    Permutation P;
    P.setNewToOld(f(A.colPtr(), A.rowIdx()));
    return P;
}

static double orderTimeFnB(const SparseMatrix<double>& A, OrderFn f) {
    { Permutation warm = fnPermutation(A, f); (void) warm; }   // warm-up, discarded

    const auto p0 = std::chrono::steady_clock::now();
    { Permutation P = fnPermutation(A, f); (void) P; }
    const auto p1 = std::chrono::steady_clock::now();
    const double one = std::chrono::duration<double, std::milli>(p1 - p0).count();
    const int repeats = std::min(std::max(static_cast<int>(targetMs / std::max(one, 1e-3)), 3), 20000);

    double best = 1e30;
    for (int trial = 0; trial < repeats; ++trial) {
        const auto t0 = std::chrono::steady_clock::now();
        { Permutation P = fnPermutation(A, f); (void) P; }
        const auto t1 = std::chrono::steady_clock::now();
        best = std::min(best, std::chrono::duration<double, std::milli>(t1 - t0).count());
    }
    return best;
}

static Permutation mmd3bPermutation(const SparseMatrix<double>& A) {
    Permutation P;
    P.setNewToOld(orderMmd3B(A.colPtr(), A.rowIdx()));
    return P;
}

